import assert from 'node:assert/strict';
import {mkdtempSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {execFileSync, spawnSync} from 'node:child_process';
import {DatabaseSync} from 'node:sqlite';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';

const binary=resolve(process.env.ORCHARD_TEST_BIN ?? `src-tauri/target/debug/orchard${process.platform==='win32'?'.exe':''}`);
const directory=mkdtempSync(join(tmpdir(),'orchard-mcp-test-'));
const database=join(directory,'inventory.sqlite3');
const cli=(...args)=>JSON.parse(execFileSync(binary,[...args,'--database',database],{encoding:'utf8'}));
let client;
try {
  const catalog=cli('catalog').result.devices;
  assert(catalog.some(d=>d.category==='ipad'));
  assert(catalog.some(d=>d.category==='mac'));
  assert(catalog.some(d=>d.id==='iphone-18-pro-max'));
  const initial=cli('status').result.status;
  assert.equal(initial.settings.enabled,false);
  assert.equal(initial.settings.target.zip_code,'');
  const db=new DatabaseSync(database);
  const now=Date.now();
  const key='apple://us/94025/iphone-duo/unlocked';
  db.prepare('INSERT INTO snapshots(id,observed_at,url,source,next_check_at) VALUES(1,?,?,?,?)').run(now-120000,key,'apple',now-60000);
  db.prepare('INSERT INTO inventory VALUES(?,?,?,?,?,?,?,?,?)').run(1,'Example Store','R001','Example City','1 mi','iPhone Duo 512GB Star White','MK1G4LL/A','available','Available Today');
  db.prepare('INSERT INTO snapshots(id,observed_at,url,source,error,next_check_at) VALUES(2,?,?,?,?,?)').run(now-30000,key,'apple','Apple inventory returned HTTP 541.',now+900000);
  db.prepare("UPDATE apple_request_gate SET not_before_ms=?,reason='cooldown' WHERE id=1").run(now+900000);
  db.close();

  const transport=new StdioClientTransport({command:binary,args:['mcp','--database',database],stderr:'pipe'});
  let stderr='';transport.stderr?.on('data',data=>{stderr+=data;});
  client=new Client({name:'orchard-sdk-verification',version:'1.0.0'},{capabilities:{}});
  await client.connect(transport);
  assert.equal(client.getServerVersion().name,'orchard');
  const listed=await client.listTools();
  assert.equal(listed.tools.length,6);
  const call=async(name,args={})=>{
    const reply=await client.callTool({name,arguments:args});
    assert.equal(reply.content[0].type,'text');
    assert.deepEqual(JSON.parse(reply.content[0].text),reply.structuredContent);
    return {reply,data:reply.structuredContent};
  };
  const target={device_id:'iphone-duo',zip_code:'94025'};
  const latest=await call('inventory_latest',target);
  assert.equal(latest.data.result.state,'unknown');
  assert.equal(latest.data.result.snapshot.current,false);
  assert.equal(latest.data.result.snapshot.available_count,1);
  const history=await call('inventory_history',{...target,limit:1});
  assert.equal(history.data.result.points.length,1);
  assert.equal(history.data.result.truncated,true);
  assert.match(history.data.result.points[0].error,/541/);
  const deferred=await call('inventory_check',{...target,connection:'browser'});
  assert.equal(deferred.reply.isError,false);
  assert.equal(deferred.data.result.state,'deferred');
  assert.equal(deferred.data.result.snapshot,null);
  assert(deferred.data.result.retry_at_ms>now);
  const invalid=await call('inventory_check',{...target,zip_code:'bad'});
  assert.equal(invalid.reply.isError,true);
  assert.match(invalid.data.error,/ZIP/);
  const unknown=await call('inventory_check',{...target,device_id:'does-not-exist'});
  assert.equal(unknown.reply.isError,true);
  await client.close();client=null;
  const after=new DatabaseSync(database);
  assert.equal(after.prepare('SELECT COUNT(*) AS n FROM snapshots').get().n,2);
  assert.equal(after.prepare('SELECT reason FROM apple_request_gate').get().reason,'cooldown');
  after.close();
  const watch=spawnSync(binary,['watch','--device','iphone-duo','--zip','94025','--timeout','1','--database',database],{encoding:'utf8',timeout:10000});
  assert.equal(watch.status,2);
  const events=watch.stdout.trim().split('\n').map(JSON.parse);
  assert.equal(events[0].result.state,'deferred');
  assert.equal(events.at(-1).state,'timeout');
  assert(!stderr.includes('panicked'),stderr);
  console.log('MCP SDK verification passed: handshake, discovery, history, unknown state, shared cooldown, validation, and bounded watch. No Apple requests made.');
} finally {
  if(client)await client.close();
  rmSync(directory,{recursive:true,force:true});
}
